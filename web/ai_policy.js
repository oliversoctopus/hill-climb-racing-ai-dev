/**
 * AI policy interface for ai_play.html.
 *
 * Contract every agent implements:
 *   async init()      Load model / allocate resources. Called once.
 *   reset()           Clear per-episode state. Called at every terrain reset.
 *   async act(ctx)    ctx = { car, ground, scale }. Returns one of:
 *                       0 = motor forward
 *                       1 = motor reverse
 *                       2 = motor off
 *
 * Adding a new agent (different obs, different model, different action enum,
 * etc.) means writing a new class here and changing one line in ai_play.html
 * (`new PpoOnnxAgent(...)` → `new MyNewAgent(...)`). No edits to the sim/render
 * code required.
 *
 * ctx.car points at the JS Car instance (Car.js). ctx.ground points at the
 * Ground instance (Ground.js). ctx.scale is the pixels-per-meter conversion.
 * Agents extract whatever they need from those.
 */
(global => {
  "use strict";

  // ----- Action enum (shared across agents) -----
  const ACT = { FORWARD: 0, REVERSE: 1, OFF: 2 };

  // ----- Obs format: single-sourced from web/policy_meta.json -----
  // The obs encoding + policy topology are generated by python/export_onnx.py from
  // python/obs_spec.py (the single source of truth) and loaded at init() below.
  // ai_policy.js does NOT keep its own copy of these constants;
  // it validates the JSON fail-closed and checks it against the ONNX input width.
  const META_FILE = "policy_meta.json";
  const REQUIRED_META_KEYS = [
    "per_wheel", "lookahead_n", "lookahead_skip", "rear_n", "rear_skip", "n_stack",
    "coyote_frames", "ang_vel_scale", "vx_scale", "vy_scale",
    "clearance_min_m", "clearance_max_m", "chassis_height_px", "n_obs", "input_width",
  ];

  // Validate a parsed policy_meta object; throw on any structural/semantic problem
  // so a bad JSON fails loudly at load instead of feeding the model garbage obs.
  function validateMeta(m) {
    if (!m || typeof m !== "object") throw new Error("policy_meta.json: not an object");
    for (let i = 0; i < REQUIRED_META_KEYS.length; i++) {
      if (!(REQUIRED_META_KEYS[i] in m)) throw new Error(`policy_meta.json: missing key '${REQUIRED_META_KEYS[i]}'`);
    }
    if (typeof m.per_wheel !== "boolean") throw new Error("policy_meta.json: per_wheel must be boolean");
    const intMins = { lookahead_n: 1, lookahead_skip: 1, rear_n: 0, rear_skip: 1, n_stack: 1,
                    coyote_frames: 0, chassis_height_px: 1, n_obs: 1, input_width: 1 };
    for (const k in intMins) {
      if (!Number.isInteger(m[k]) || m[k] < intMins[k])
        throw new Error(`policy_meta.json: ${k} must be an integer >= ${intMins[k]} (got ${m[k]})`);
    }
    const positive = ["ang_vel_scale", "vx_scale", "vy_scale"];
    for (let j = 0; j < positive.length; j++) {
      if (!(typeof m[positive[j]] === "number" && m[positive[j]] > 0))
        throw new Error(`policy_meta.json: ${positive[j]} must be a positive number`);
    }
    if (!(m.clearance_min_m < m.clearance_max_m))
      throw new Error("policy_meta.json: clearance_min_m must be < clearance_max_m");
    const expObs = (m.per_wheel ? 6 : 5) + m.lookahead_n + m.rear_n;
    if (m.n_obs !== expObs)
      throw new Error(`policy_meta.json: n_obs ${m.n_obs} != base+lookahead+rear ${expObs}`);
    if (m.input_width !== m.n_obs * m.n_stack)
      throw new Error(`policy_meta.json: input_width ${m.input_width} != n_obs*n_stack ${m.n_obs * m.n_stack}`);
  }

  /**
   * SB3 PPO policy exported to ONNX via python/export_onnx.py.
   *
   * Encapsulates:
   *   - ONNX Runtime Web session loading (one session per instance, but ORT
   *     internally shares the WASM module across sessions so memory is fine
   *     for 1-2 AI players).
   *   - The exact obs construction from python/env.py (angle wrap + coyote
   *     groundedness + velocity normalizations + 6 ground-clearance samples).
   *   - A 4-deep frame stack matching SB3's VecFrameStack (oldest first,
   *     newest last; pre-filled on reset).
   *   - Argmax over action logits.
   *
   * Per-episode state (frame stack, coyote counter) is reset via reset().
   * The session itself persists across resets — it's expensive to reload.
   */
  function PpoOnnxAgent(modelPath) {
    this.modelPath = modelPath;
    this.session = null;
    this.meta = null;          // obs spec, loaded + validated from policy_meta.json in init()
    // Coyote counters — one per wheel when meta.per_wheel; both used for
    // backward compat (single-bit mode reuses _lastGroundedRear).
    this._lastGroundedRear  = 0;
    this._lastGroundedFront = 0;
    this._frameStack = [];
    // Scratch buffers are sized in init() once the obs width is known from meta.
    this._obsScratch = null;
    this._stackedScratch = null;
  }

  PpoOnnxAgent.prototype.init = async function() {
    if (typeof ort === "undefined") {
      throw new Error("ONNX Runtime Web (ort.min.js) not loaded before agent init");
    }
    // 1) Load + validate the obs spec (fail-closed: a missing/bad meta throws).
    const metaPath = this.modelPath.replace(/[^/]*$/, "") + META_FILE;
    let resp;
    try {
      resp = await fetch(metaPath);
    } catch (e) {
      throw new Error(`policy_meta.json fetch failed (${metaPath}): ${e.message} — serve over http:// (not file://) and re-export the model.`);
    }
    if (!resp.ok) throw new Error(`policy_meta.json not found at ${metaPath} (HTTP ${resp.status})`);
    await this._initWith(await resp.json(), this.modelPath);
  };

  // Init from in-memory bytes (dev mode's "load a model file"): meta = parsed JSON,
  // modelBytes = Uint8Array of the .onnx. Same validation as init().
  PpoOnnxAgent.prototype.initFromBytes = async function(modelBytes, meta) {
    if (typeof ort === "undefined") throw new Error("ONNX Runtime Web (ort.min.js) not loaded before agent init");
    await this._initWith(meta, modelBytes);
  };

  PpoOnnxAgent.prototype._initWith = async function(meta, modelSrc) {
    validateMeta(meta);
    this.meta = meta;
    this._obsScratch = new Float32Array(meta.n_obs);
    this._stackedScratch = new Float32Array(meta.input_width);

    // 2) Create the ONNX session.
    // Single-threaded WASM; SIMD if available. Threading needs cross-origin
    // isolation HTTP headers which our static server doesn't set.
    ort.env.wasm.numThreads = 1;
    ort.env.wasm.simd = true;
    this.session = await ort.InferenceSession.create(modelSrc, {
      executionProviders: ["wasm"],
    });

    // 3) Model-width check: a dummy inference of the declared input width. If the
    // meta disagrees with the ONNX model's actual input, this throws at load.
    try {
      await this.session.run({
        observation: new ort.Tensor("float32", new Float32Array(meta.input_width), [1, meta.input_width]),
      });
    } catch (e) {
      throw new Error(`policy_meta.json input_width ${meta.input_width} does not match the ONNX model input (${typeof modelSrc === "string" ? modelSrc : "uploaded model"}): ${e.message}`);
    }
  };

  PpoOnnxAgent.prototype.reset = function() {
    this._lastGroundedRear = 0;
    this._lastGroundedFront = 0;
    this._frameStack = [];
    this.lastLogits = null;
  };

  // Snapshot / restore the agent's resumable per-episode state (frame stack +
  // coyote counters). Used by the in-browser backtracking ("save-scum") search so
  // the policy resumes with the EXACT obs history it had at a rewind point — the
  // browser analogue of python/autorun/backtrack_search.py snapshotting the
  // VecFrameStack + env coyote counters. Deep-copies the frame buffers.
  PpoOnnxAgent.prototype.snapshotState = function() {
    const fs = [];
    for (let i = 0; i < this._frameStack.length; i++) fs.push(new Float32Array(this._frameStack[i]));
    return { lgr: this._lastGroundedRear, lgf: this._lastGroundedFront, fs };
  };
  PpoOnnxAgent.prototype.restoreState = function(s) {
    this._lastGroundedRear = s.lgr;
    this._lastGroundedFront = s.lgf;
    this._frameStack = [];
    for (let i = 0; i < s.fs.length; i++) this._frameStack.push(new Float32Array(s.fs[i]));
  };

  PpoOnnxAgent.prototype.act = async function(ctx) {
    const obs = this._buildObs(ctx);
    this._pushFrame(obs);
    const stacked = this._buildStacked();
    const result = await this.session.run({
      observation: new ort.Tensor("float32", stacked, [1, this.meta.input_width]),
    });
    const logits = result.action_logits.data;   // Float32Array(3)
    let a = ACT.FORWARD;
    if (logits[ACT.REVERSE] > logits[a]) a = ACT.REVERSE;
    if (logits[ACT.OFF]     > logits[a]) a = ACT.OFF;
    this.lastLogits = logits;   // read by dev mode's AI-vision overlay; not used for acting
    return a;
  };

  // -------- Internal helpers --------

  // Build the obs vector from the loaded meta spec. Mirrors
  // python/env.py._build_obs; both derive their constants from obs_spec, so they
  // agree by construction. Shape depends on meta.per_wheel:
  //   - false: single grounded bit
  //   - true:  separate rear + front grounded bits
  PpoOnnxAgent.prototype._buildObs = function(ctx) {
    const car = ctx.car, ground = ctx.ground, SCALE = ctx.scale;
    const m = this.meta;
    const c = car.chassisBody;
    const p = c.GetPosition();
    const v = c.GetLinearVelocity();
    const angle = c.GetAngle();
    const angVel = c.GetAngularVelocity();
    // wheels[0] = rear (left at spawn), wheels[1] = front (right at spawn).
    const rearGround  = (car.wheels[0].onGround === true);
    const frontGround = (car.wheels[1].onGround === true);
    const obs = this._obsScratch;
    let idx = 0;

    // [0] chassis angle, wrapped through (a+PI) mod 2*PI -> [0, 1]
    let aa = angle;
    while (aa < 0) aa += 2 * Math.PI;
    aa = (aa + Math.PI) % (2 * Math.PI);
    obs[idx++] = aa / (2 * Math.PI);

    // Groundedness with coyote frames: persist "grounded=1" for N ticks after liftoff.
    if (m.per_wheel) {
      this._lastGroundedRear += 1;
      if (rearGround) this._lastGroundedRear = 0;
      obs[idx++] = (this._lastGroundedRear < m.coyote_frames) ? 1.0 : 0.0;
      this._lastGroundedFront += 1;
      if (frontGround) this._lastGroundedFront = 0;
      obs[idx++] = (this._lastGroundedFront < m.coyote_frames) ? 1.0 : 0.0;
    } else {
      this._lastGroundedRear += 1;
      if (rearGround || frontGround) {
        this._lastGroundedRear = 0;
        obs[idx++] = 1.0;
      } else {
        obs[idx++] = (this._lastGroundedRear < m.coyote_frames) ? 1.0 : 0.0;
      }
    }

    // angular + linear velocity, normalized + clipped to [-1, 1].
    obs[idx++] = Math.max(-1, Math.min(1, angVel / m.ang_vel_scale));
    obs[idx++] = Math.max(-1, Math.min(1, v.x / m.vx_scale));
    obs[idx++] = Math.max(-1, Math.min(1, v.y / m.vy_scale));

    // ground-clearance samples ahead of chassis_x, normalized to [-1, 1].
    const clearanceCenter = (m.clearance_max_m + m.clearance_min_m) / 2;
    const clearanceHalf   = (m.clearance_max_m - m.clearance_min_m) / 2;
    const chassisBottomYm = p.y + m.chassis_height_px / SCALE;
    const samplesM = ground.getPositions(p.x, m.lookahead_n, m.lookahead_skip);
    for (let i = 0; i < m.lookahead_n; i++) {
      const posYm = (i < samplesM.length) ? samplesM[i] : samplesM[samplesM.length - 1];
      let cc = posYm - chassisBottomYm;
      if (cc < m.clearance_min_m) cc = m.clearance_min_m;
      if (cc > m.clearance_max_m) cc = m.clearance_max_m;
      obs[idx++] = (cc - clearanceCenter) / clearanceHalf;
    }

    // Rear ground-clearance samples, same encoding. Mirrors js_backend.getRear +
    // python/env.py: walk backward from the first vertex at/after chassis_x.
    // Ground.js vectors are in meters.
    if (m.rear_n > 0) {
      const rearM = this._getRear(ground, p.x, m.rear_n, m.rear_skip);
      for (let k = 0; k < m.rear_n; k++) {
        const ry = (k < rearM.length) ? rearM[k] : rearM[rearM.length - 1];
        let rc = ry - chassisBottomYm;
        if (rc < m.clearance_min_m) rc = m.clearance_min_m;
        if (rc > m.clearance_max_m) rc = m.clearance_max_m;
        obs[idx++] = (rc - clearanceCenter) / clearanceHalf;
      }
    }
    return obs;
  };

  // Backward counterpart to Ground.getPositions: n ground y-values (meters)
  // behind x at -skip, -2*skip, ... vertices (closest-behind first).
  PpoOnnxAgent.prototype._getRear = (ground, x, n, skip) => {
    const vs = ground.vectors;
    let idx = -1;
    for (let i = 0; i < vs.length; i++) {
      if (vs[i].x >= x) { idx = i; break; }
    }
    if (idx < 0) idx = vs.length - 1;
    const out = [];
    for (let k = 1; k <= n; k++) {
      let j = idx - k * skip;
      if (j < 0) j = 0;
      out.push(vs[j].y);   // meters, matches getPositions
    }
    return out;
  };

  // Push the new obs into a 4-frame stack matching SB3's VecFrameStack:
  // oldest first, newest last. On reset, pre-fill with the first observation.
  PpoOnnxAgent.prototype._pushFrame = function(obs) {
    if (this._frameStack.length === 0) {
      // Note: we push a COPY because _obsScratch is reused next tick. Without
      // copying, all stack slots would alias the same buffer and update
      // together — the policy would only ever see one frame of history.
      const copy = new Float32Array(obs);
      for (let i = 0; i < this.meta.n_stack; i++) this._frameStack.push(new Float32Array(copy));
    } else {
      this._frameStack.shift();
      this._frameStack.push(new Float32Array(obs));
    }
  };

  PpoOnnxAgent.prototype._buildStacked = function() {
    const out = this._stackedScratch;
    for (let i = 0; i < this.meta.n_stack; i++) {
      out.set(this._frameStack[i], i * this.meta.n_obs);
    }
    return out;
  };

  // ----- Example: stub agent for testing without ONNX -----
  // Drives forward constantly. Useful for verifying the env loop works
  // without a model loaded.
  function ConstantForwardAgent() {}
  ConstantForwardAgent.prototype.init = async () => {};
  ConstantForwardAgent.prototype.reset = () => {};
  ConstantForwardAgent.prototype.act = async ctx => ACT.FORWARD;

  // ----- Exports -----
  global.AiPolicy = {
    ACT,
    PpoOnnxAgent,
    ConstantForwardAgent,
  };
})(window);
